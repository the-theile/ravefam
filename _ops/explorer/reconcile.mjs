#!/usr/bin/env node
// One-time page -> DB reconcile, run before the Explorer switches to being
// generated from Supabase (build-explorer.mjs).
//
// Emits a migration that only ADDS to the DB, never overwrites or removes:
//   * fills `night` on appearances that have none, matching each DB row to
//     the page card for the same artist (same start time, else same stage,
//     else the first unclaimed card), plus b2b_group / stage / set times where
//     the DB has none;
//   * is_headliner = page OR db;
//   * inserts a row for every page card the DB lacks (extra sets of
//     multi-set acts, artists never synced);
//   * leaves DB-only rows and conflicting values alone (drift report lists them).
// Lineup-alert triggers are switched off for the transaction: these acts were
// already public on the Explorer, so fans shouldn't get "just added" pings.
// ALERT_SLUGS=slug-a,slug-b inserts those festivals' new acts with alerts ON.
//
//   [ALERT_SLUGS=...] node reconcile.mjs slug-a slug-b ...   (default: every lineup page)
// Writes ../../supabase/migrations/<stamp>_explorer_reconcile.sql
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT, festivalFiles, readPage, pageRows } from './pages.mjs';

const only = new Set(process.argv.slice(2));
// Festivals whose newly added acts SHOULD alert the fans who follow them:
// their inserts run after the alert triggers are back on.
const ALERT_SLUGS = (process.env.ALERT_SLUGS || '').split(',').filter(Boolean);
const STAMP = process.env.STAMP || '20261117030000';
const OUT = path.join(ROOT, 'supabase/migrations', `${STAMP}_explorer_reconcile.sql`);

const rows = [];
for (const { slug, file } of festivalFiles()) {
  if (only.size && !only.has(slug)) continue;
  for (const r of pageRows(readPage(file))) {
    rows.push([slug, r.artist, r.night, r.stage, r.start, r.end, r.hl, r.b2b_group, r.card, r.sync]);
  }
}
const slugs = [...new Set(rows.map(r => r[0]))];
const alertArray = `array[${ALERT_SLUGS.map(s => `'${s}'`).join(', ')}]::text[]`;
const insertSql = cond => `insert into public.artist_festival_appearances
  (artist_id, festival_id, night, b2b_group, stage, start_at, end_at, is_headliner, time_official)
select p.artist_id, p.festival_id, p.night, p.b2b_group, p.stage,
       p.start_local::timestamp at time zone p.timezone,
       case when p.end_local is not null and p.start_local is not null
             and p.end_local > p.start_local
             and p.end_local::timestamp <= p.start_local::timestamp + interval '12 hours'
            then p.end_local::timestamp at time zone p.timezone end,
       p.hl, p.start_local is not null
from _pr p
where p.matched_id is null and ${cond}
  and (p.start_local is null or p.timezone is not null)
on conflict do nothing;
`;
const json = JSON.stringify(rows).replace(/'/g, "''");

const sql = `-- Generated by _ops/explorer/reconcile.mjs. Do not edit by hand.
-- One-time page -> DB reconcile for ${slugs.length} festival(s) before the Lineup
-- Explorer is generated from Supabase. Only fills gaps and adds missing rows;
-- never overwrites a DB value or removes a row. See docs/explorer-drift-2026-11-17.md.
-- Page rows: [slug, artist, night, stage, start_local, end_local, hl, b2b_group, card, sync]

alter table public.artist_festival_appearances disable trigger afa_lineup_alerts_insert;
alter table public.artist_festival_appearances disable trigger afa_lineup_alerts_set_times;

create temp table _pr as
select r.slug, trim(r.artist) as artist, lower(trim(r.artist)) as artist_lower,
       nullif(r.night, '') as night, nullif(r.stage, '') as stage,
       case when r.sync then nullif(r.start_local, '') end as start_local,
       case when r.sync then nullif(r.end_local, '') end as end_local,
       coalesce(r.hl, false) as hl, nullif(r.b2b, '') as b2b_group, r.card,
       f.id as festival_id, f.timezone, null::bigint as artist_id, null::bigint as matched_id
from jsonb_to_recordset((
       select jsonb_agg(jsonb_build_object(
         'slug', e->>0, 'artist', e->>1, 'night', e->>2, 'stage', e->>3,
         'start_local', e->>4, 'end_local', e->>5, 'hl', (e->>6)::boolean,
         'b2b', e->>7, 'card', (e->>8)::int, 'sync', (e->>9)::boolean))
       from jsonb_array_elements('${json}'::jsonb) e))
     as r(slug text, artist text, night text, stage text, start_local text, end_local text,
          hl boolean, b2b text, card int, sync boolean)
join public.festivals f on f.slug = r.slug and f.deleted_at is null;

insert into public.artists (name)
select distinct on (artist_lower) artist from _pr order by artist_lower, artist
on conflict (name_lower) do nothing;

update _pr p set artist_id = a.id from public.artists a where a.name_lower = p.artist_lower;

do $$
declare
  a record;
  m record;
  v_start timestamptz;
  v_end   timestamptz;
begin
  -- Match each existing DB row to one page card (exact night first, then a
  -- night-less DB row to the best card), claiming cards as we go.
  for a in
    select x.*, p_tz.timezone
    from public.artist_festival_appearances x
    join (select distinct festival_id, timezone from _pr) p_tz on p_tz.festival_id = x.festival_id
    order by (x.night is null), x.festival_id, x.artist_id, x.start_at nulls last, x.id
  loop
    select p.* into m from _pr p
    where p.festival_id = a.festival_id and p.artist_id = a.artist_id and p.matched_id is null
      and (a.night is null or lower(a.night) = p.night or p.night is null)
    order by
      (a.night is not null and lower(a.night) = p.night) desc,
      (a.start_at is not null and p.start_local is not null
        and p.start_local::timestamp at time zone a.timezone = a.start_at) desc,
      ((a.note ilike '%b2b%' or a.b2b_group is not null) = (p.b2b_group is not null)) desc,
      (a.stage is not null and p.stage = a.stage) desc,
      p.card
    limit 1;
    continue when not found;

    update _pr set matched_id = a.id
    where festival_id = m.festival_id and artist_id = m.artist_id and card = m.card;

    v_start := coalesce(a.start_at, m.start_local::timestamp at time zone a.timezone);
    v_end   := coalesce(a.end_at, case when a.start_at is null
                                       then m.end_local::timestamp at time zone a.timezone end);
    if v_end is not null and (v_start is null or v_end <= v_start
                              or v_end > v_start + interval '12 hours') then
      v_end := a.end_at;
    end if;

    begin
      update public.artist_festival_appearances set
        night        = coalesce(night, m.night),
        b2b_group    = coalesce(b2b_group, m.b2b_group),
        stage        = coalesce(stage, m.stage),
        start_at     = v_start,
        end_at       = v_end,
        is_headliner = is_headliner or m.hl,
        time_official = time_official or (start_at is null and v_start is not null)
      where id = a.id;
    exception when unique_violation then
      -- another row already holds this artist+night+note+b2b; leave this one as is
      null;
    end;
  end loop;
end $$;

-- Page cards with no DB row: insert them (alerts off).
${insertSql(`not (p.slug = any(${alertArray}))`)}
alter table public.artist_festival_appearances enable trigger afa_lineup_alerts_insert;
alter table public.artist_festival_appearances enable trigger afa_lineup_alerts_set_times;
${ALERT_SLUGS.length ? `
-- Alerts ON for: ${ALERT_SLUGS.join(', ')}. These acts were on the Explorer page but
-- never in the app, so fans who follow them get an "artist added" alert now.
${insertSql(`p.slug = any(${alertArray})`)}` : ''}`;

writeFileSync(OUT, sql);
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${rows.length} page rows across ${slugs.length} festival(s), ${(sql.length / 1024).toFixed(1)} KB`);
